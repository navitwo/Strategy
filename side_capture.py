def canonical_side_spec_sha256(specs=SIDE_SPECS):
    payload = json.dumps(specs, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()


def matched_side(instrument, source_x):
    """Return the captured +/-1 side for a source row, fail-closed."""
    return SIDE_SPECS[str(instrument).upper()][int(source_x)]


def validate_side_spec(specs=SIDE_SPECS):
    expected = {"NQ": 385, "ES": 185, "YM": 376, "RTY": 171}
    assert {k: len(v) for k, v in specs.items()} == expected
    assert canonical_side_spec_sha256(specs) == SIDE_SPEC_SHA256
    for instrument, mapping in specs.items():
        assert all(side in (-1, 1) for side in mapping.values())
        assert len(mapping) == len(set(mapping))
    return True
